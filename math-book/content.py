# ---------- helpers -------------------------------------------------------
def E(q, a, chk=None, text=False, hint=None, ahtml=False):
    """An exercise. q/a are LaTeX unless text=True (q and a are HTML)."""
    return dict(q=q, a=a, chk=chk, text=text, hint=hint, ahtml=ahtml or text)

def eq(expr, ans):          # expr and ans must be identical for every x, y
    return ("eq", expr, ans)

def sysc(eqs, sol):         # each item of eqs is "lhs - (rhs)"; sol = (x, y)
    return ("sys", eqs, sol)


