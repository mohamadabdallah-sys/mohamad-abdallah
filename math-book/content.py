def TF(s, truth, fix=None, chk=None):
    """True/false item. s and fix are HTML. chk is ("eq", a, b) or ("pt", eqs, (x, y));
    the check result must equal `truth`."""
    return dict(s=s, truth=truth, fix=fix, chk=chk)

def pt(eqs, p):            # does the point p satisfy all equations?
    return ("pt", eqs, p)

