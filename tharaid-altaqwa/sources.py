def details(rest):
    r = re.sub(r"^[،:\s.]+", "", rest)
    r = re.sub(r"(?:المجلد|الجزء)\s*", "ج ", r)
    r = re.sub(r"(?:الصفحة|ص\s*:)\s*", "ص ", r)
    r = re.sub(r"(?:الحديث\s+رقم|رقم\s+الحديث|حديث\s+رقم|الحديث|حديث)\s*", "ح ", r)
    r = re.sub(r"\bح\s*\(?(\d+)\)?", r"ح \1", r)
    r = re.sub(r"^\s*(\d+)\s*/\s*(\d+)(?:\s*/\s*(\d+))?", lambda m: "ج %s، ص %s" % (m.group(1), m.group(2)) + ("، ح %s" % m.group(3) if m.group(3) else ""), r)
    r = re.sub(r"\(\s*(باب[^()]*)\)", r"\1", r)
    r = re.sub(r"\s*/\s*", "، ", r)
    r = re.sub(r"\s*،\s*", "، ", r)
    r = re.sub(r"^[،:\s.]+|[،:\s.]+$", "", r)
    r = re.sub(r"(ص \d+)\s*و\s*(\d+)", r"\1–\2", r)
    r = re.sub(r"(\d)\s+(باب|كتاب)", r"\1، \2", r)
    r = re.sub(r"\s*\(ت \d+ هـ?\)", "", r)
    r = re.sub(r"[.،]\s*\(", " (", r)
    r = re.sub(r"،\s*الشيخ$", "", r)
    r = r.replace(" – ", "، ")
    return r


def canon_segment(seg):
    s = seg.strip()
    for pat, name, author in BOOKS:
        m = re.search(pat, s)
        if not m:
            continue
        before, after = s[:m.start()], s[m.end():]
        prefix = ""
        pm = re.match(r"^\s*(ينظر في معناه:|ينظر:|وروي مضمون[^:]*في)\s*", before)
        if pm:
            prefix = pm.group(1) + " "
            before = before[pm.end():]
        if re.sub(r"(%s)|[،:\s.]" % AUTHORS, "", before).strip():
            return seg.strip()                       # something else in front: leave it alone
        after = re.sub(r"^[،:\s]*(?:(?:%s)[،\s]*)+" % AUTHORS, "", after)
        after = re.sub(r"[،\s]*(?:%s)\s*$" % AUTHORS, "", after)
        after = re.sub(r"،\s*كتاب\s+الكافي", "", after)
        d = details(after)
        out = prefix + name + ("، " + author if author else "")
        return out + ("، " + d if d else "")
    return seg.strip()


def canon(note):
    note = note.strip().rstrip(".")
    parts = re.split(r"\s*؛\s*|\s+/\s+", note)
    out = []
    for p in parts:
        p = re.sub(r"^و(?=[^\s]{3})", "", p) if out else p
        out.append(canon_segment(p))
    res = "؛ و".join([out[0]] + out[1:]) if len(out) > 1 else out[0]
    return correct(res)


